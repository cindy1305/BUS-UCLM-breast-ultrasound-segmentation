def plot_segmentation_result(gray, gt_binary, pred_mask, debug, metrics):
    """
    Visualiza:
    1. Imagen original.
    2. Imagen preprocesada.
    3. Contraste local oscuro.
    4. Candidatos.
    5. Máscara predicha.
    6. Overlay GT vs Pred.
    """

    gray_resized = cv2.resize(gray, SIZE, interpolation=cv2.INTER_LINEAR)

    if gt_binary.shape != pred_mask.shape:
        gt_binary = cv2.resize(
            gt_binary,
            (pred_mask.shape[1], pred_mask.shape[0]),
            interpolation=cv2.INTER_NEAREST
        )

    overlay = cv2.cvtColor(gray_resized, cv2.COLOR_GRAY2RGB)

    intersection = np.logical_and(pred_mask == 1, gt_binary == 1)
    only_gt = np.logical_and(pred_mask == 0, gt_binary == 1)
    only_pred = np.logical_and(pred_mask == 1, gt_binary == 0)

    overlay[intersection] = [255, 255, 0]  # amarillo = coincidencia
    overlay[only_gt] = [0, 255, 0]         # verde = GT no detectado
    overlay[only_pred] = [255, 0, 0]       # rojo = falso positivo

    plt.figure(figsize=(22, 4))

    plt.subplot(1, 6, 1)
    plt.imshow(gray_resized, cmap="gray")
    plt.title("Original")
    plt.axis("off")

    plt.subplot(1, 6, 2)
    plt.imshow(debug["preprocessed"], cmap="gray")
    plt.title("Preprocesada")
    plt.axis("off")

    plt.subplot(1, 6, 3)
    plt.imshow(debug["local_dark"], cmap="gray")
    plt.title("Contraste local oscuro")
    plt.axis("off")

    plt.subplot(1, 6, 4)
    plt.imshow(debug["candidate"], cmap="gray")
    plt.title("Candidatos")
    plt.axis("off")

    plt.subplot(1, 6, 5)
    plt.imshow(pred_mask, cmap="gray")
    plt.title("Máscara predicha")
    plt.axis("off")

    plt.subplot(1, 6, 6)
    plt.imshow(overlay)
    plt.title(f"GT vs Pred\nDice={metrics['Dice']:.3f}, IoU={metrics['IoU']:.3f}")
    plt.axis("off")

    plt.tight_layout()
    plt.show()

